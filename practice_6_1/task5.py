# При оформлені посилки заборонено перевозити наступні речі:
# ножі
# гроші
# сильні отрути
# Виправіть помилку в коді
items = input("Введіть ваші речі: ")
items = items.lower()

if "ножі" in items or "гроші" in items or "сильні отрути" in items:
    print("У вас є речі які заборонено перевозити")
else:
    print("Оформлено доставку")
